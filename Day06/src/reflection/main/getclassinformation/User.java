package com.reflection.getclassinformation;

// Defining a class for object mapping
public class User {
	private String name;
	private int age;

	// Defining a constructor
	public User() {
	}

	// Defining a method to display user details
	public void display() {
		System.out.println("User Name: " + name);
		System.out.println("User Age: " + age);
	}
}

